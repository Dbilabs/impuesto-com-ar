#!/usr/bin/env python3
"""
scripts/sync_skills.py
Single Source of Truth compiler for impuesto.com.ar Skills.

Reads all skills-pack/<slug>/SKILL.md files and generates:
  1. functions/mcp/skills_bundle.js  -> Imported directly by Cloudflare Pages MCP Worker (all 8 subdomains!)
  2. dist/skills/<slug>/SKILL.md     -> Direct downloadable SKILL.md files
  3. dist/skills/manifest.json       -> Versioned catalog with SHA-256 hashes for auto-update checks
  4. dist/skills/install.sh          -> 1-line installer for Claude Code, Gemini/Antigravity, Cursor & Codex
  5. dist/skills/index.html          -> Clean hub page at https://impuesto.com.ar/skills/
"""

import os
import re
import json
import hashlib
import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = ROOT / "skills-pack"
OUT_JS = ROOT / "functions" / "mcp" / "skills_bundle.js"
DIST_SKILLS = ROOT / "dist" / "skills"


def parse_frontmatter(text: str):
    meta = {}
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip('"').strip("'")
    return meta


def main():
    skills = []
    for skill_file in sorted(SKILLS_DIR.glob("*/SKILL.md")):
        slug = skill_file.parent.name
        content = skill_file.read_text(encoding="utf-8")
        meta = parse_frontmatter(content)
        sha = hashlib.sha256(content.encode("utf-8")).hexdigest()[:12]
        skills.append({
            "slug": slug,
            "uri": f"skill://impuesto/{slug}",
            "name": meta.get("name", f"impuesto-{slug}"),
            "description": meta.get("description", ""),
            "version": meta.get("version", "2.0.0"),
            "perfil_objetivo": meta.get("perfil_objetivo", "todos"),
            "sha256": sha,
            "download_url": f"https://impuesto.com.ar/skills/{slug}/SKILL.md",
            "content": content,
        })

    built_at = datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")

    # 1. Generate functions/mcp/skills_bundle.js
    OUT_JS.parent.mkdir(parents=True, exist_ok=True)
    js_payload = (
        f"// AUTO-GENERATED by scripts/sync_skills.py at {built_at} — DO NOT EDIT MANUALLY.\n"
        f"// Single Source of Truth: skills-pack/*/SKILL.md\n\n"
        f"export const SKILLS_BUILT_AT = {json.dumps(built_at)};\n"
        f"export const SKILLS_BUNDLE = {json.dumps(skills, ensure_ascii=False, indent=2)};\n"
    )
    OUT_JS.write_text(js_payload, encoding="utf-8")

    # 2. Generate dist/skills/<slug>/SKILL.md + manifest.json
    DIST_SKILLS.mkdir(parents=True, exist_ok=True)
    manifest_items = []
    for s in skills:
        dest = DIST_SKILLS / s["slug"]
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "SKILL.md").write_text(s["content"], encoding="utf-8")
        manifest_items.append({k: v for k, v in s.items() if k != "content"})

    manifest = {
        "publisher": "impuesto.com.ar",
        "built_at": built_at,
        "total_skills": len(skills),
        "mcp_endpoints": [
            "https://claude.impuesto.com.ar",
            "https://chatgpt.impuesto.com.ar",
            "https://gemini.impuesto.com.ar",
            "https://copilot.impuesto.com.ar",
            "https://cursor.impuesto.com.ar",
            "https://perplexity.impuesto.com.ar",
            "https://mcp.impuesto.com.ar",
            "https://api.impuesto.com.ar",
        ],
        "skills": manifest_items,
    }
    (DIST_SKILLS / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")

    # 3. Generate dist/skills/install.sh (1-line installer for Claude Code / Gemini / Antigravity / Cursor / Codex)
    slugs_str = " ".join(s["slug"] for s in skills)
    install_sh = f"""#!/usr/bin/env bash
set -euo pipefail

echo "⚡ Instalando Skill Pack oficial de impuesto.com.ar (5 skills ARCA + Double-Check)..."
SLUGS=({slugs_str})
TARGETS=()

[ -d "$HOME/.claude" ] && TARGETS+=("$HOME/.claude/skills")
[ -d "$HOME/.gemini/config" ] && TARGETS+=("$HOME/.gemini/config/skills")
[ -d "$HOME/.cursor" ] && TARGETS+=("$HOME/.cursor/skills")
[ -d "$HOME/.codex" ] && TARGETS+=("$HOME/.codex/skills")

if [ ${{#TARGETS[@]}} -eq 0 ]; then
  TARGETS=("$HOME/.claude/skills" "$HOME/.gemini/config/skills")
fi

for BASE in "${{TARGETS[@]}}"; do
  for SLUG in "${{SLUGS[@]}}"; do
    DIR="$BASE/impuesto-$SLUG"
    mkdir -p "$DIR"
    curl -fsSL "https://impuesto.com.ar/skills/$SLUG/SKILL.md" -o "$DIR/SKILL.md"
  done
  echo "✅ Instalado en: $BASE"
done

echo ""
echo "🎉 Listo. Conectá el MCP en tu asistente:"
echo "   • Claude:   https://claude.impuesto.com.ar"
echo "   • ChatGPT:  https://chatgpt.impuesto.com.ar"
echo "   • Gemini:   https://gemini.impuesto.com.ar"
echo "   • Copilot:  https://copilot.impuesto.com.ar"
"""
    (DIST_SKILLS / "install.sh").write_text(install_sh, encoding="utf-8")

    # 4. Generate dist/skills/index.html (clean hub page)
    cards_html = ""
    for s in skills:
        cards_html += f"""
      <div class="card">
        <div class="meta"><span class="badge">{s['perfil_objetivo']}</span> <span class="ver">v{s['version']} · {s['sha256']}</span></div>
        <h3>{s['name']}</h3>
        <p>{s['description']}</p>
        <div class="actions">
          <a class="btn" href="/skills/{s['slug']}/SKILL.md" download="{s['name']}.md">Descargar SKILL.md</a>
          <code class="uri">{s['uri']}</code>
        </div>
      </div>"""

    index_html = f"""<!doctype html>
<html lang="es-AR">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Skills Oficiales — impuesto.com.ar</title>
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<style>
:root{{--ink:#0B1320;--muted:#475467;--line:#E3E7EC;--bg:#F8FAFC;--acc:#0B6E4F;--acc2:#074F39;--tint:#E7F5EF;--font:system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}}
*{{box-sizing:border-box}}
body{{margin:0;font-family:var(--font);color:var(--ink);background:var(--bg);padding:40px 20px;line-height:1.6}}
.wrap{{max-width:920px;margin:0 auto}}
.hero{{background:#fff;border:1px solid var(--line);border-radius:18px;padding:32px;margin-bottom:24px;box-shadow:0 12px 32px rgba(15,27,45,.05)}}
.pill{{background:var(--tint);color:var(--acc2);font-weight:700;font-size:12.5px;padding:4px 12px;border-radius:99px;display:inline-block;margin-bottom:10px}}
h1{{margin:0 0 10px;font-size:30px;letter-spacing:-.025em}}
p{{color:var(--muted);margin:0 0 16px}}
.cmd{{background:#0B1320;color:#E7F5EF;padding:14px 18px;border-radius:12px;font-family:ui-monospace,SFMono-Regular,Consolas,monospace;font-size:13.5px;display:flex;justify-content:space-between;align-items:center;gap:12px;overflow-x:auto}}
.cmd button{{background:var(--acc);color:#fff;border:0;padding:8px 12px;border-radius:8px;font-weight:600;cursor:pointer;white-space:nowrap}}
.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(280px,1fr));gap:16px}}
.card{{background:#fff;border:1px solid var(--line);border-radius:14px;padding:22px;display:flex;flex-direction:column;justify-content:space-between}}
.meta{{display:flex;justify-content:space-between;align-items:center;margin-bottom:8px;font-size:12px}}
.badge{{background:var(--tint);color:var(--acc2);font-weight:700;padding:2px 8px;border-radius:99px;text-transform:uppercase}}
.ver{{color:var(--muted);font-family:ui-monospace,monospace}}
h3{{margin:0 0 8px;font-size:17px}}
.card p{{font-size:14px;margin-bottom:16px}}
.actions{{display:flex;flex-direction:column;gap:8px}}
.btn{{background:var(--acc);color:#fff;text-decoration:none;text-align:center;padding:9px 14px;border-radius:9px;font-weight:600;font-size:13.5px}}
.btn:hover{{background:var(--acc2)}}
.uri{{font-size:12px;color:var(--muted);background:#F4F6F9;padding:5px 8px;border-radius:6px;text-align:center}}
</style>
</head>
<body>
<div class="wrap">
  <div class="hero">
    <span class="pill">Single Source of Truth · Sincronizado con los 8 servidores MCP</span>
    <h1>Skill Packs Oficiales de impuesto.com.ar</h1>
    <p>Todos los skills se sirven en vivo vía <strong>MCP Resources</strong> (cero instalación requerida en Claude/ChatGPT/Gemini) y también podés instalarlos localmente en 1 comando para Claude Code, Gemini CLI, Antigravity, Cursor o Codex:</p>
    <div class="cmd">
      <span>curl -fsSL https://impuesto.com.ar/skills/install.sh | bash</span>
      <button onclick="navigator.clipboard.writeText('curl -fsSL https://impuesto.com.ar/skills/install.sh | bash');this.innerText='¡Copiado!'">Copiar</button>
    </div>
  </div>
  <div class="grid">{cards_html}
  </div>
</div>
</body>
</html>
"""
    (DIST_SKILLS / "index.html").write_text(index_html, encoding="utf-8")
    print(f"✅ Synced {len(skills)} skills -> {OUT_JS} & {DIST_SKILLS}")


if __name__ == "__main__":
    main()
